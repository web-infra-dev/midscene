import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const reportTemplateMagicString = 'REPLACE_ME_WITH_REPORT_HTML';
export const reportTemplateMaxBytes = 3 * 1024 * 1024;

export const reportTemplateModulePaths = {
  cjs: 'lib/report-html-template.js',
  esm: 'es/report-html-template.mjs',
};

const reportDumpOpeningTag =
  '<script type="midscene_web_dump" type="application/json" data-group-id="';
const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const defaultCoreDistDir = path.join(repositoryRoot, 'packages/core/dist');
const defaultReportTemplatePath = path.join(
  repositoryRoot,
  'apps/report/dist/index.html',
);

function validateReportTemplateSize(size, label) {
  if (size > reportTemplateMaxBytes) {
    throw new Error(
      `${label} exceeds the 3 MiB size limit (${size} bytes). This may indicate recursive Report template bundling.`,
    );
  }
}

export function validateReportHtml(html) {
  if (typeof html !== 'string' || !html.trim()) {
    throw new Error('Report template is empty.');
  }
  validateReportTemplateSize(
    Buffer.byteLength(html, 'utf8'),
    'Report template',
  );
  if (html.includes(reportTemplateMagicString)) {
    throw new Error('Report template contains an unresolved placeholder.');
  }
  if (!/<!doctype html>/i.test(html)) {
    throw new Error('Report template does not contain <!doctype html>.');
  }
  if (!/id=["']root["']/.test(html)) {
    throw new Error('Report template does not contain the root mount point.');
  }

  const documentCount = (html.match(/<!doctype html>/gi) || []).length;
  if (documentCount !== 1) {
    throw new Error(
      `Report template must contain exactly one HTML document, found ${documentCount}.`,
    );
  }
  if (html.includes(reportDumpOpeningTag)) {
    throw new Error(
      'Report bundle must not include Agent report HTML generation code.',
    );
  }

  return html;
}

export function renderReportTemplateModules(html) {
  const validatedHtml = validateReportHtml(html);
  const serializedHtml = JSON.stringify(validatedHtml);
  const generatedHeader = '// Generated by @midscene/report. Do not edit.\n';

  return {
    cjs: `${generatedHeader}'use strict';\nexports.REPORT_HTML_TEMPLATE = ${serializedHtml};\n`,
    esm: `${generatedHeader}export const REPORT_HTML_TEMPLATE = ${serializedHtml};\n`,
  };
}

export function writeReportTemplateModules(coreDistDir, html) {
  const modules = renderReportTemplateModules(html);
  const writtenFiles = [];

  for (const [format, relativePath] of Object.entries(
    reportTemplateModulePaths,
  )) {
    const filePath = path.join(coreDistDir, relativePath);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, modules[format]);
    writtenFiles.push(filePath);
  }

  return writtenFiles;
}

export function syncCoreReportTemplateModules({
  coreDistDir = defaultCoreDistDir,
  reportTemplatePath = defaultReportTemplatePath,
} = {}) {
  if (!fs.existsSync(reportTemplatePath)) {
    throw new Error(`Report template not found at ${reportTemplatePath}.`);
  }

  return writeReportTemplateModules(
    coreDistDir,
    fs.readFileSync(reportTemplatePath, 'utf8'),
  );
}

export function validateCoreReportTemplateModules(
  coreDistDir,
  { reportTemplatePath = defaultReportTemplatePath } = {},
) {
  if (!fs.existsSync(reportTemplatePath)) {
    throw new Error(`Report template not found at ${reportTemplatePath}.`);
  }
  validateReportTemplateSize(
    fs.statSync(reportTemplatePath).size,
    `Report template at ${reportTemplatePath}`,
  );
  const validatedExpectedHtml = validateReportHtml(
    fs.readFileSync(reportTemplatePath, 'utf8'),
  );

  for (const relativePath of Object.values(reportTemplateModulePaths)) {
    const filePath = path.join(coreDistDir, relativePath);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Core report template module not found at ${filePath}.`);
    }

    validateReportTemplateSize(
      fs.statSync(filePath).size,
      `Core report template module at ${filePath}`,
    );
    const content = fs.readFileSync(filePath, 'utf8');
    if (content.includes(reportTemplateMagicString)) {
      throw new Error(`Core report template is not written in ${filePath}.`);
    }
    const assignmentIndex = content.indexOf(' = ');
    const assignmentEndIndex = content.lastIndexOf(';');
    if (assignmentIndex === -1 || assignmentEndIndex === -1) {
      throw new Error(`Invalid Core report template module at ${filePath}.`);
    }

    let html;
    try {
      html = JSON.parse(
        content.slice(assignmentIndex + ' = '.length, assignmentEndIndex),
      );
    } catch (error) {
      throw new Error(
        `Cannot parse Core report template module at ${filePath}: ${error}`,
      );
    }
    const validatedHtml = validateReportHtml(html);
    if (validatedHtml !== validatedExpectedHtml) {
      throw new Error(
        `Core report template does not match the current Report build in ${filePath}.`,
      );
    }
  }
}
